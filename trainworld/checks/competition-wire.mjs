import assert from 'node:assert/strict';
import { compactContext, compactResult, expandResult } from '../app/src/game/competitionWire.ts';
const companies=Array.from({length:5},(_,i)=>({id:'company-'+i,name:'Company '+i,cash:10000,revenue:0,running:0,upkeep:0,spent:0,fleet:[0,0,0,0,0]}));
const owners=Object.fromEntries(Array.from({length:10000},(_,i)=>['edge:'+i,companies[i%5].id]));
const before={clock:0,cash:50000,rate:0,fares:{base:1,perKm:1},ledger:[],competition:{companies,owners}};
const after={...before,competition:{companies,owners:{...owners,'edge:10000':'company-0'}}};
const result={before,after,answer:{ok:true,issues:[],charge:0}};
const packed=compactResult(result),decoded=expandResult(packed,owners);
assert.deepEqual(decoded.before,before);assert.deepEqual(decoded.after,after);
assert.deepEqual(packed.ownershipDelta,{'edge:10000':'company-0'});
assert(JSON.stringify(packed).length<4096);
assert(JSON.stringify(result).length>400000);
assert.equal(Object.keys(compactContext(after).competition.owners).length,0);
const deleted=compactResult({...result,before:after,after:before});
assert.equal(deleted.ownershipDelta['edge:10000'],null);
assert.deepEqual(expandResult(deleted,after.competition.owners).after,before);
assert.equal(expandResult(result,{}),result);
console.log('PASS 10,000-asset ownership delta, deletion, legacy replay and bounded event size',JSON.stringify({fullBytes:JSON.stringify(result).length,deltaBytes:JSON.stringify(packed).length}));
